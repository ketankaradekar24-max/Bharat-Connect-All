type InstitutionSeed = typeof institutions.$inferInsert;

const now = new Date();
const nextQuarter = new Date(now.getTime() + 90 * 24 * 60 * 60 * 1000);

function makeInstitution(input: {
  slug: string;
  name: string;
  shortName: string;
  category: string;
  institutionType: string;
  primaryStream: string;
  streams: string[];
  state: string;
  city: string;
  campuses?: string[];
  coursesOffered: string[];
  entranceExamsAccepted: string[];
  admissionRoutes: Array<{
    routeName: string;
    examOrBasis: string;
    counsellingAuthority: string;
    eligibility: string;
    notes: string;
  }>;
  overview: string;
  affiliatedCollegesInfo?: string | null;
  ugAdmissionsInfo: string;
  pgAdmissionsInfo?: string | null;
  lateralEntryInfo?: string | null;
  quotaAndCounsellingInfo: string;
  feesInfo?: string;
  feesReliability?: 'verified_range' | 'official_bulletin';
  scholarshipsInfo?: string;
  officialWebsiteUrl: string;
  officialAdmissionUrl: string;
  sourceUrl?: string;
}): InstitutionSeed {
  return {
    slug: input.slug,
    name: input.name,
    shortName: input.shortName,
    category: input.category,
    institutionType: input.institutionType,
    primaryStream: input.primaryStream,
    streams: input.streams,
    state: input.state,
    city: input.city,
    campuses: input.campuses ?? [`${input.city}, ${input.state}`],
    coursesOffered: input.coursesOffered,
    entranceExamsAccepted: input.entranceExamsAccepted,
    admissionRoutes: input.admissionRoutes,
    overview: input.overview,
    affiliatedCollegesInfo: input.affiliatedCollegesInfo ?? null,
    ugAdmissionsInfo: input.ugAdmissionsInfo,
    pgAdmissionsInfo: input.pgAdmissionsInfo ?? null,
    lateralEntryInfo: input.lateralEntryInfo ?? null,
    quotaAndCounsellingInfo: input.quotaAndCounsellingInfo,
    feesInfo:
      input.feesInfo ??
      'Check official university fee notification / prospectus or state Fee Regulatory Committee order for current academic year tuition & exam fees.',
    feesReliability: input.feesReliability ?? 'official_bulletin',
    scholarshipsInfo:
      input.scholarshipsInfo ??
      'Eligible students can apply for National Scholarship Portal (NSP), State Scholarship portals (e.g., Karnataka SSP), and institutional merit-cum-means waivers.',
    officialWebsiteUrl: input.officialWebsiteUrl,
    officialAdmissionUrl: input.officialAdmissionUrl,
    sourceUrl: input.sourceUrl ?? input.officialWebsiteUrl,
    verificationStatus: 'verified',
    publishStatus: 'published',
    lastVerifiedAt: now,
    nextReviewAt: nextQuarter,
  };
}

