const now = new Date();
const nextQuarter = new Date(now.getTime() + 90 * 24 * 60 * 60 * 1000);

function makeExpandedExam(input: {
  slug: string;
  examName: string;
  fullName: string;
  category: string;
  subcategory: string;
  tags: string[];
  conductingAuthority: string;
  jurisdiction?: string;
  state?: string;
  examPurpose: string;
  whoShouldApply: string;
  eligibility: string;
  ageLimit: string;
  qualificationRequirements: string;
  examPattern: string;
  syllabusSummary: string;
  importantDatesText?: string;
  registrationInfo: string;
  applicationFee?: string;
  requiredDocuments?: string[];
  applicationSteps?: string[];
  admitCardInfo?: string;
  prepResources?: Array<{ title: string; url: string; source: string }>;
  previousPapersInfo?: string;
  previousPapersUrl?: string | null;
  resultsInfo?: string;
  counsellingProcess?: string;
  officialWebsiteUrl: string;
  officialApplyUrl: string;
  officialNotificationUrl: string;
}): ExamSeed {
  return {
    slug: input.slug,
    examName: input.examName,
    fullName: input.fullName,
    category: input.category,
    subcategory: input.subcategory,
    tags: input.tags,
    conductingAuthority: input.conductingAuthority,
    jurisdiction: input.jurisdiction ?? 'Central',
    state: input.state ?? 'All India',
    examPurpose: input.examPurpose,
    whoShouldApply: input.whoShouldApply,
    eligibility: input.eligibility,
    ageLimit: input.ageLimit,
    qualificationRequirements: input.qualificationRequirements,
    examPattern: input.examPattern,
    syllabusSummary: input.syllabusSummary,
    importantDatesText:
      input.importantDatesText ??
      'Dates not announced — check official notification on the conducting authority website.',
    nextExamDate: null,
    registrationInfo: input.registrationInfo,
    applicationFee:
      input.applicationFee ??
      'Check official Information Bulletin for current category-wise examination fee.',
    requiredDocuments: input.requiredDocuments ?? [
      'Recent passport-size photograph & scanned signature as per portal pixel/size rules',
      'Valid Government Photo ID (Aadhaar / PAN / Passport / Voter ID)',
      'Class 10 & Class 12 / Diploma / Qualifying Degree marks cards',
      'Category / EWS / PwD / Domicile certificate in prescribed format (if applicable)',
    ],
    applicationSteps: input.applicationSteps ?? [
      `Visit the official portal (${input.officialWebsiteUrl}) and read the active Information Brochure carefully.`,
      'Complete online registration using an active email ID and mobile number to generate your Application Number.',
      'Fill personal, academic, domicile/category, and examination center preferences.',
      'Upload scanned photograph, signature, and supporting certificates in specified formats.',
      'Pay the official fee online on the conducting portal and retain the Confirmation Page PDF.',
    ],
    admitCardInfo:
      input.admitCardInfo ??
      'Admit cards / Hall Tickets are downloaded directly from the official portal using Application Number and Password/DOB.',
    prepResources: input.prepResources ?? [
      {
        title: 'NCERT Official Textbooks & Exemplar',
        url: 'https://ncert.nic.in/textbook.php',
        source: 'NCERT',
      },
      {
        title: 'SWAYAM / NPTEL Free Official Video Courses',
        url: 'https://swayam.gov.in/',
        source: 'Ministry of Education',
      },
    ],
    previousPapersInfo:
      input.previousPapersInfo ??
      'Refer to the official Downloads / Archive / Mock Test section on the conducting authority portal.',
    previousPapersUrl: input.previousPapersUrl ?? null,
    resultsInfo:
      input.resultsInfo ??
      'Provisional answer keys, scorecards, and merit/rank lists are published strictly on the official portal.',
    counsellingProcess:
      input.counsellingProcess ??
      'Qualified candidates participate in official centralized, state, or university-level counselling rounds.',
    officialWebsiteUrl: input.officialWebsiteUrl,
    officialApplyUrl: input.officialApplyUrl,
    officialNotificationUrl: input.officialNotificationUrl,
    verificationStatus: 'verified',
    publishStatus: 'published',
    lastVerifiedAt: now,
    nextReviewAt: nextQuarter,
  };
}

