export async function ensureExpandedExams(): Promise<void> {
  // 1. Insert new dedicated exams cleanly
  await db
    .insert(exams)
    .values(EXPANDED_VERIFIED_EXAMS)
    .onConflictDoNothing({ target: exams.slug });

  // 2. Update tags & unannounced cycle text on existing baseline records
  for (const item of BASELINE_EXAM_UPDATES) {
    await db
      .update(exams)
      .set({
        tags: item.tags,
        ...(item.importantDatesText ? { importantDatesText: item.importantDatesText } : {}),
        updatedAt: new Date(),
      })
      .where(eq(exams.slug, item.slug));
  }

  // 3. Archive legacy combined summary entries now replaced by dedicated records
  //    so users see clean dedicated cards for MET, SRMJEEE, AEEE, OJEE, KIITEE,
  //    AIAPGET, Nursing, Pharmacy, Veterinary, and Allied Health.
  for (const legacySlug of ['met-manipal-srmjeee-ojee-aeee', 'aiapget-nursing-pharmacy-allied']) {
    await db
      .update(exams)
      .set({ publishStatus: 'archived', updatedAt: new Date() })
      .where(eq(exams.slug, legacySlug));
  }
}
