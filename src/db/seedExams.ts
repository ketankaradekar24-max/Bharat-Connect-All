type ExamSeed = typeof exams.$inferInsert;

const now = new Date();
const nextQuarter = new Date(now.getTime() + 90 * 24 * 60 * 60 * 1000);

function makeExam(input: {
  slug: string;
  examName: string;
  fullName: string;
  category: string;
  subcategory: string;
  conductingAuthority: string;
  jurisdiction?: string;
  state?: string;
  examPurpose: string;
  whoShouldApply: string;
  eligibility: string;
  ageLimit: string;
  qualificationRequirements: string;
  examPattern: string;
  syllabusSummary: string;
  importantDatesText?: string;
  registrationInfo: string;
  applicationFee?: string;
  requiredDocuments?: string[];
  applicationSteps?: string[];
  admitCardInfo?: string;
  prepResources?: Array<{ title: string; url: string; source: string }>;
  previousPapersInfo?: string;
  previousPapersUrl?: string | null;
  resultsInfo?: string;
  counsellingProcess?: string;
  officialWebsiteUrl: string;
  officialApplyUrl: string;
  officialNotificationUrl: string;
}): ExamSeed {
  return {
    slug: input.slug,
    examName: input.examName,
    fullName: input.fullName,
    category: input.category,
    subcategory: input.subcategory,
    conductingAuthority: input.conductingAuthority,
    jurisdiction: input.jurisdiction ?? 'Central',
    state: input.state ?? 'All India',
    examPurpose: input.examPurpose,
    whoShouldApply: input.whoShouldApply,
    eligibility: input.eligibility,
    ageLimit: input.ageLimit,
    qualificationRequirements: input.qualificationRequirements,
    examPattern: input.examPattern,
    syllabusSummary: input.syllabusSummary,
    importantDatesText:
      input.importantDatesText ??
      'Dates vary each cycle; verify the active Information Bulletin on the official exam website before registering.',
    nextExamDate: null,
    registrationInfo: input.registrationInfo,
    applicationFee:
      input.applicationFee ??
      'Information not yet verified for the current cycle — check the official Information Bulletin fee schedule.',
    requiredDocuments: input.requiredDocuments ?? [
      'Recent passport-size photograph & scanned signature as per specification',
      'Valid Government Photo ID (PAN / Passport / Voter ID / Aadhaar per official portal guidelines)',
      'Class 10 & Class 12 / Qualifying Degree marks cards and certificates',
      'Category / PwD / EWS / Domicile certificate in prescribed format (if claiming reservation)',
    ],
    applicationSteps: input.applicationSteps ?? [
      `Visit the official portal (${input.officialWebsiteUrl}) and download the current Information Bulletin.`,
      'Complete online registration using an active email ID and mobile number to generate your Application Number.',
      'Fill personal, academic, category, and exam-city preference details accurately.',
      'Upload scanned photograph, signature, and applicable eligibility certificates in prescribed pixel/size limits.',
      'Pay the official examination fee directly on the portal and save the Confirmation Page PDF.',
    ],
    admitCardInfo:
      input.admitCardInfo ??
      'Admit cards / Hall Tickets are released exclusively on the official exam portal using your Application Number and Date of Birth/Password.',
    prepResources: input.prepResources ?? [
      {
        title: 'NCERT Official Textbooks & Exemplar Problems',
        url: 'https://ncert.nic.in/textbook.php',
        source: 'NCERT',
      },
      {
        title: 'SWAYAM / NPTEL Free Official Video Courses',
        url: 'https://swayam.gov.in/',
        source: 'Ministry of Education',
      },
    ],
    previousPapersInfo:
      input.previousPapersInfo ??
      'Check the official Downloads / Archive / Mock Test section on the conducting authority website for authentic previous question papers.',
    previousPapersUrl: input.previousPapersUrl ?? null,
    resultsInfo:
      input.resultsInfo ??
      'Scorecards, merit lists, and cut-off percentiles are published on the official exam portal after final answer key review.',
    counsellingProcess:
      input.counsellingProcess ??
      'Qualified candidates participate in centralized or state-level counselling / verification as notified by the official admission or recruitment authority.',
    officialWebsiteUrl: input.officialWebsiteUrl,
    officialApplyUrl: input.officialApplyUrl,
    officialNotificationUrl: input.officialNotificationUrl,
    verificationStatus: 'verified',
    publishStatus: 'published',
    lastVerifiedAt: now,
    nextReviewAt: nextQuarter,
  };
}

